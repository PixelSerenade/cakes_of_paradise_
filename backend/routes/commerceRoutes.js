const express = require('express');
const commerce = require('../controllers/commerceController');
const promoCampaigns = require('../controllers/promoCampaignController');
const { protect } = require('../middleware/authMiddleware');
const { requireRole } = require('../middleware/roleMiddleware');
const router = express.Router();
const asyncRoute = (handler) => (req, res, next) => Promise.resolve(handler(req, res, next)).catch(next);
router.post('/promotions/validate', protect, asyncRoute(commerce.validatePromo));
router.post('/gift-cards/check', asyncRoute(commerce.checkGiftCard));
router.post('/gift-cards/claim', protect, asyncRoute(commerce.claimGiftCard));
router.get('/gift-wallet', protect, asyncRoute(commerce.getGiftWallet));
router.get('/gift-card-offers', asyncRoute(commerce.listCustomerGiftCardOffers));
router.post('/gift-cards/purchase', asyncRoute(commerce.createGiftCardPurchase));
router.post('/gift-cards/purchase/wallet', protect, asyncRoute(commerce.createGiftCardWalletPurchase));
router.post('/gift-cards/purchase/wallet/:purchaseId/deliver', protect, asyncRoute(commerce.retryGiftCardWalletDelivery));
router.post('/gift-cards/purchase/verify', asyncRoute(commerce.verifyGiftCardPurchase));
router.get('/admin/gift-card-offers', protect, requireRole('admin'), asyncRoute(commerce.listAdminGiftCardOffers));
router.post('/admin/gift-card-offers', protect, requireRole('admin'), asyncRoute(commerce.createGiftCardOffer));
router.put('/admin/gift-card-offers/:id', protect, requireRole('admin'), asyncRoute(commerce.updateGiftCardOffer));
router.patch('/admin/gift-card-offers/:id/status', protect, requireRole('admin'), asyncRoute(commerce.setGiftCardOfferActive));
router.get('/admin/promotions', protect, requireRole('admin'), asyncRoute(commerce.listPromos));
router.post('/admin/promotions', protect, requireRole('admin'), asyncRoute(commerce.createPromo));
router.patch('/admin/promotions/:id', protect, requireRole('admin'), asyncRoute(commerce.setPromoActive));
router.get('/admin/promo-campaigns', protect, requireRole('admin'), asyncRoute(promoCampaigns.list));
router.post('/admin/promo-campaigns', protect, requireRole('admin'), asyncRoute(promoCampaigns.create));
router.get('/admin/gift-cards', protect, requireRole('admin'), asyncRoute(commerce.listGiftCards));
router.post('/admin/gift-cards', protect, requireRole('admin'), asyncRoute(commerce.issueGiftCard));
router.get('/admin/gift-cards/activity', protect, requireRole('admin'), asyncRoute(commerce.listGiftCardActivity));
router.get('/admin/gift-cards/:id', protect, requireRole('admin'), asyncRoute(commerce.getAdminGiftCard));
router.put('/admin/gift-cards/:id', protect, requireRole('admin'), asyncRoute(commerce.updateAdminGiftCard));
router.patch('/admin/gift-cards/:id/status', protect, requireRole('admin'), asyncRoute(commerce.setGiftCardActive));
module.exports = router;
