const mongoose = require('mongoose');

const orderSchema = new mongoose.Schema({
  orderNumber: { type: String, required: true, unique: true, index: true },
  user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
  customer: {
    name: { type: String, required: true },
    email: { type: String, required: true },
    phone: { type: String, required: true },
    address: { type: String, required: true },
    area: { type: String, default: '' },
    city: { type: String, default: '' },
    postalCode: { type: String, default: '' },
    deliveryType: { type: String, enum: ['delivery', 'pickup'], default: 'delivery' },
    deliveryDate: { type: Date, required: true },
    deliveryTime: { type: String, default: '', match: [/^(?:[01]\d|2[0-3]):[0-5]\d$/, 'Use a valid delivery time'] },
    notes: { type: String, default: '' },
  },
  items: [{
    productId: { type: String, required: true },
    name: { type: String, required: true },
    image: { type: String, required: true },
    flavor: { type: String, required: true },
    size: { type: String, required: true },
    cakeMessage: { type: String, trim: true, maxlength: 50, default: '' },
    unitPrice: { type: Number, required: true },
    quantity: { type: Number, required: true, min: 1 },
  }],
  total: { type: Number, required: true, min: 0 },
  subtotal: { type: Number, required: true, min: 1 },
  deliveryFee: { type: Number, default: 0, min: 0 },
  deliveryDistanceBand: { type: String, default: '' },
  loyaltyPointsRedeemed: { type: Number, default: 0, min: 0 },
  loyaltyPointsEarned: { type: Number, default: 0, min: 0 },
  loyaltyPointsRefunded: { type: Boolean, default: false },
  discountAmount: { type: Number, default: 0, min: 0 },
  promoCode: { type: String, default: '' },
  referralCode: { type: String, default: '' },
  promoUsageRefunded: { type: Boolean, default: false },
  giftCardAmount: { type: Number, default: 0, min: 0 },
  giftWalletAmount: { type: Number, default: 0, min: 0 },
  giftWalletRefunded: { type: Boolean, default: false },
  giftCardLast4: { type: String, default: '' },
  giftCardRef: { type: mongoose.Schema.Types.ObjectId, ref: 'GiftCard', default: null },
  giftCardRefunded: { type: Boolean, default: false },
  stockRestored: { type: Boolean, default: false },
  paymentMethod: { type: String, enum: ['razorpay', 'pay-at-pickup', 'pay-on-delivery', 'pay-at-store', 'gift-card', 'promotion'], required: true },
  // pending/failed are retained for existing records; new orders use unpaid.
  paymentStatus: { type: String, enum: ['unpaid', 'paid', 'refund-due', 'refunded', 'pending', 'failed'], default: 'unpaid' },
  paymentOrderId: { type: String, default: '' },
  paymentId: { type: String, default: '' },
  paidAt: { type: Date, default: null },
  paidBy: { type: String, default: '' },
  trackingNumber: { type: String, default: '', trim: true, maxlength: 100 },
  shippingCarrier: { type: String, default: '', trim: true, maxlength: 100 },
  estimatedDelivery: { type: Date, default: null },
  orderConfirmationEmailStatus: { type: String, enum: ['pending', 'sending', 'sent', 'failed', 'not_configured'], default: 'pending' },
  orderConfirmationEmailSentAt: { type: Date, default: null },
  orderConfirmationEmailStartedAt: { type: Date, default: null },
  paymentConfirmationEmailStatus: { type: String, enum: ['pending', 'sending', 'sent', 'failed', 'not_configured'], default: 'pending' },
  paymentConfirmationEmailSentAt: { type: Date, default: null },
  paymentConfirmationEmailStartedAt: { type: Date, default: null },
  orderShippedEmailStatus: { type: String, enum: ['pending', 'sending', 'sent', 'failed', 'not_configured'], default: 'pending' },
  orderShippedEmailSentAt: { type: Date, default: null },
  orderShippedEmailStartedAt: { type: Date, default: null },
  refundStatus: { type: String, enum: ['none', 'pending', 'processed', 'failed'], default: 'none' },
  refundId: { type: String, default: '' },
  refundedAmount: { type: Number, default: 0, min: 0 },
  cancellationReason: { type: String, default: '', maxlength: 240 },
  status: {
    type: String,
    enum: ['placed', 'confirmed', 'preparing', 'ready', 'shipped', 'out-for-delivery', 'completed', 'cancelled'],
    default: 'placed',
  },
  tracking: [{
    type: { type: String, enum: ['status', 'payment', 'refund'], default: 'status' },
    status: { type: String, required: true },
    from: { type: String, default: '' },
    to: { type: String, default: '' },
    note: { type: String, default: '' },
    at: { type: Date, default: Date.now },
    changedBy: { type: String, default: 'system' },
  }],
}, { timestamps: true });

orderSchema.index({ status: 1, createdAt: -1 });
orderSchema.index({ status: 1, paymentStatus: 1, createdAt: -1 });
orderSchema.index({ paymentStatus: 1, createdAt: -1 });
orderSchema.index({ createdAt: -1 });

module.exports = mongoose.model('Order', orderSchema);
